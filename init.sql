

CREATE TABLE aircraft (
                          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          aircraft_type VARCHAR(32)  NOT NULL,
                          tail_number   VARCHAR(32)  NOT NULL UNIQUE
);

CREATE TABLE compartments (
                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              name        VARCHAR(64)       NOT NULL,
                              max_weight  DOUBLE PRECISION  NOT NULL,
                              aircraft_id BIGINT            NOT NULL REFERENCES aircraft(id) ON DELETE CASCADE,
                              CHECK (max_weight > 0)
);

CREATE TABLE flight (
                        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        flight_number    VARCHAR(32)       NOT NULL,
                        status           VARCHAR(16)       NOT NULL,
                        departure_time   TIMESTAMP(6)      NOT NULL,
                        passenger_weight DOUBLE PRECISION,
                        aircraft_id      BIGINT            REFERENCES aircraft(id),
                        CHECK (passenger_weight IS NULL OR passenger_weight >= 0)
);

CREATE TABLE cargo (
                       id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       weight         DOUBLE PRECISION  NOT NULL,
                       description    VARCHAR(255),
                       added_at       TIMESTAMP(6)      NOT NULL,
                       flight_id      BIGINT            NOT NULL REFERENCES flight(id) ON DELETE CASCADE,
                       compartment_id BIGINT            NOT NULL REFERENCES compartments(id) ON DELETE RESTRICT,
                       CHECK (weight > 0)
);

CREATE TABLE resources (
                           id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           resource_type      VARCHAR(16)       NOT NULL,
                           name               VARCHAR(128)      NOT NULL,
                           assigned_flight_id BIGINT            REFERENCES flight(id),
                           model_name         VARCHAR(64),
                           capacity           DOUBLE PRECISION  DEFAULT 0,
                           specialization     VARCHAR(64),
                           size               INT               DEFAULT 1,
                           CHECK (resource_type IN ('EQUIPMENT', 'BRIGADE'))
);

